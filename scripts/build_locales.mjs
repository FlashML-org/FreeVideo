// Keep JSON as the editable source of truth. Emit a synchronous browser ES module,
// avoiding a runtime network request or JSON import-attribute browser dependency.
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';
const root = new URL('../web/locales/', import.meta.url);
const languages = ['en', 'zh', 'pt-BR'];
const catalogs = Object.fromEntries(languages.map(lang => [lang, JSON.parse(fs.readFileSync(new URL(lang+'.json', root), 'utf8'))]));
const keys = Object.keys(catalogs.en).sort();
for (const lang of languages) {
    for (const [key, value] of Object.entries(catalogs[lang])) {
        if (!Object.hasOwn(catalogs.en, key) || typeof value !== 'string' || !value.trim()) throw new Error(lang+': invalid entry '+key);
    }
    for (const key of keys) if (!Object.hasOwn(catalogs[lang], key)) throw new Error(lang+': missing '+key);
}
const source = '// Generated by scripts/build_locales.mjs. Edit locales/*.json instead.\nexport const catalogs = '+JSON.stringify(catalogs, null, 2)+';\n';
const output = fileURLToPath(new URL('catalogs.js', root));
if (process.argv.includes('--check')) {
    if (fs.readFileSync(output, 'utf8').replace(/\r\n/g,'\n') !== source) throw new Error('Locale bundle is stale; run node scripts/build_locales.mjs');
} else fs.writeFileSync(output, source);
